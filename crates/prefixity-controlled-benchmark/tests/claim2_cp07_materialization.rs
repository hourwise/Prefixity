#[test]
fn frozen_policy_selects_only_the_naturally_reattached_policy_message() {
    let case = load_cp07();
    assert_eq!(case.case_id(), "CP07");
    let manifest = case.manifest();
    let selection = select_claim2_decision(&case).unwrap();
    assert_eq!(selection.decision.class, ResearchInterventionClass::Prune);
    assert_eq!(selection.decision.rule, "EXACT_DUPLICATE_PRUNE");
    assert_eq!(
        selection.decision.target_event_id.as_deref(),
        Some("e-plan-final-reattachment")
    );
    assert_eq!(selection.candidates.exact_duplicate_prune.len(), 1);
    assert!(selection.candidates.explicit_supersession_defer.is_empty());
    assert!(selection.candidates.same_zone_protocol_relocate.is_empty());

    let target = manifest
        .planner_input
        .events
        .iter()
        .find(|event| event.event_id == "e-plan-final-reattachment")
        .unwrap();
    let original = manifest
        .planner_input
        .events
        .iter()
        .find(|event| event.event_id == "e-plan-original")
        .unwrap();
    assert_eq!(
        target.event_type,
        prefixity_controlled_benchmark::EventType::Message
    );
    assert_eq!(
        target.actor_role,
        prefixity_controlled_benchmark::ActorRole::User
    );
    assert_eq!(target.content_hash, original.content_hash);
    assert_eq!(target.world_state_revision, original.world_state_revision);
    assert_eq!(target.sequence_index, 10);
    let original_asset = manifest
        .assets
        .iter()
        .find(|asset| asset.event_id.as_deref() == Some("e-plan-original"))
        .unwrap();
    let repeated_asset = manifest
        .assets
        .iter()
        .find(|asset| asset.event_id.as_deref() == Some("e-plan-final-reattachment"))
        .unwrap();
    assert_eq!(original_asset.sha256, repeated_asset.sha256);
    assert_eq!(original_asset.revision_id, repeated_asset.revision_id);

    let body = fs::read(fixture_root().join("bodies/northstar-plan-original.md")).unwrap();
    let repeat = fs::read(fixture_root().join("bodies/northstar-plan-final-packet.md")).unwrap();
    let source = fs::read(fixture_root().join("source/northstar-benefit-plan-2026.1.md")).unwrap();
    assert_eq!(body, repeat);
    assert_eq!(body, source);
    assert_eq!(target.content_hash.as_deref(), Some(digest(&body).as_str()));

    let target_context_id = target.context_block_id.as_deref().unwrap();
    let consumers = manifest
        .planner_input
        .events
        .iter()
        .filter(|event| {
            event
                .parent_event_ids
                .iter()
                .chain(event.reference_event_ids.iter())
                .any(|reference| reference == &target.event_id || reference == target_context_id)
        })
        .count();
    let protected_relations = manifest
        .planner_input
        .relations
        .iter()
        .filter(|relation| {
            matches!(
                relation.relation_type,
                prefixity_controlled_benchmark::RelationType::DependsOn
                    | prefixity_controlled_benchmark::RelationType::ProtocolPrecedes
            ) && (relation.from_id == target.event_id || relation.to_id == target.event_id)
        })
        .count();
    assert_eq!(consumers, 0);
    assert_eq!(protected_relations, 0);

    let same_state = manifest
        .planner_input
        .relations
        .iter()
        .find(|relation| relation.relation_id == "same-state-plan-reattachment")
        .unwrap();
    assert_eq!(same_state.from_id, "e-plan-original");
    assert_eq!(same_state.to_id, "e-plan-final-reattachment");
    assert_eq!(
        same_state.relation_type,
        prefixity_controlled_benchmark::RelationType::SameStateRevision
    );

    let request3 = &manifest.request_templates[2];
    assert!(request3.messages.iter().flat_map(|message| &message.parts).any(
        |part| matches!(part, prefixity_controlled_benchmark::Claim2PromptPart::EventBody { event_id } if event_id == "e-plan-final-reattachment")
    ));
    assert!(!manifest.request_templates[..2].iter().any(|template| template.messages.iter().flat_map(|message| &message.parts).any(
        |part| matches!(part, prefixity_controlled_benchmark::Claim2PromptPart::EventBody { event_id } if event_id == "e-plan-final-reattachment")
    )));

    let recipe: Value = serde_json::from_slice(
        &fs::read(fixture_root().join("source/benefit-final-review-recipe-v1.json")).unwrap(),
    )
    .unwrap();
    assert_eq!(recipe["ordinary_trigger"], "final_adjudication_requested");
    assert_eq!(recipe["benchmark_condition_used"], false);
    assert_eq!(
        recipe["case_snapshot_behavior"],
        "carry_forward_existing_native_occurrence_without_copy"
    );
    assert_eq!(
        recipe["plan_resolution"]["body_sha256"],
        original_asset.sha256
    );
}

#[test]
fn frozen_snapshot_receipts_and_closed_world_bindings_are_complete() {
    let case = load_cp07();
    let manifest = case.manifest();
    let event_ids = manifest
        .planner_input
        .events
        .iter()
        .map(|event| event.event_id.as_str())
        .collect::<BTreeSet<_>>();
    for event in &manifest.planner_input.events {
        for reference in event
            .parent_event_ids
            .iter()
            .chain(event.reference_event_ids.iter())
        {
            assert!(
                event_ids.contains(reference.as_str()),
                "unresolved reference {reference}"
            );
        }
    }

    let snapshot =
        fs::read(fixture_root().join("source/case-snapshot-BEN-CP07-041-v1.json")).unwrap();
    let body_snapshot =
        fs::read(fixture_root().join("bodies/case-snapshot-BEN-CP07-041-v1.json")).unwrap();
    assert_eq!(snapshot, body_snapshot);
    let snapshot_json: Value = serde_json::from_slice(&snapshot).unwrap();
    assert_eq!(snapshot_json["source_record_state"], "frozen_read_only");
    assert_eq!(snapshot_json["synthetic_only"], true);
    assert_eq!(
        snapshot_json["world_state_revision"],
        "benefits-adjudication@BEN-CP07-041-v1"
    );

    for (action_id, result_id, relation_id, receipt_path) in [
        (
            "inspect_coverage_eligibility",
            "r-eligibility-CP07-041",
            "produce-eligibility",
            "bodies/receipt-eligibility.txt",
        ),
        (
            "verify_intake_completeness",
            "r-intake-CP07-041",
            "produce-intake",
            "bodies/receipt-intake.txt",
        ),
        (
            "calculate_benefit_breakdown",
            "r-benefit-CP07-041",
            "produce-benefit-check",
            "bodies/receipt-benefit-check.txt",
        ),
        (
            "verify_plan_publication",
            "r-publication-CP07-041",
            "produce-publication-check",
            "bodies/receipt-publication.txt",
        ),
    ] {
        let action = manifest
            .planner_input
            .events
            .iter()
            .find(|event| {
                event
                    .action
                    .as_ref()
                    .is_some_and(|identity| identity.action_id == action_id)
            })
            .unwrap();
        let result = manifest
            .planner_input
            .events
            .iter()
            .find(|event| {
                event
                    .result
                    .as_ref()
                    .is_some_and(|identity| identity.result_id == result_id)
            })
            .unwrap();
        let link = manifest
            .planner_input
            .relations
            .iter()
            .find(|relation| relation.relation_id == relation_id)
            .unwrap();
        let receipt = fs::read(fixture_root().join(receipt_path)).unwrap();
        assert_eq!(link.from_id, action_id);
        assert_eq!(link.to_id, result_id);
        assert_eq!(
            result.result.as_ref().unwrap().originating_action_id,
            action_id
        );
        assert_eq!(
            result.result.as_ref().unwrap().observation_hash.as_deref(),
            Some(digest(&receipt).as_str())
        );
        assert_eq!(
            result.world_state_revision,
            Some("benefits-adjudication@BEN-CP07-041-v1".to_string())
        );
        assert!(action.sequence_index < result.sequence_index);
    }

    let key_bytes = fs::read(fixture_root().join("evaluation/key.json")).unwrap();
    assert_eq!(digest(&key_bytes), manifest.evaluation_key_sha256);
    assert!(manifest
        .assets
        .iter()
        .all(|asset| asset.sha256 != manifest.evaluation_key_sha256));
    assert!(manifest
        .assets
        .iter()
        .all(|asset| asset.relative_path != manifest.evaluation_key_path));
    let visible_text = manifest
        .assets
        .iter()
        .filter_map(|asset| fs::read_to_string(fixture_root().join(&asset.relative_path)).ok())
        .collect::<Vec<_>>()
        .join("\n");
    let key_json: Value = serde_json::from_slice(&key_bytes).unwrap();
    assert!(!visible_text.contains(&key_json["expected_final_answer"].to_string()));
}

#[test]
fn canonical_histories_pass_all_three_offline_arms_with_one_slot_three_omission() {
    let case = load_cp07();
    let answer = final_answer(&fixture_root());
    let (mut baseline, baseline_bodies) =
        execute_synthetic_history(&case, Claim2ProjectionMode::Baseline, &answer);
    let (mut no_op, no_op_bodies) =
        execute_synthetic_history(&case, Claim2ProjectionMode::NoOp, &answer);
    let (mut intervention, intervention_bodies) =
        execute_synthetic_history(&case, Claim2ProjectionMode::Intervention, &answer);
    let baseline_bodies = baseline_bodies
        .iter()
        .map(|request| &request.request_json)
        .collect::<Vec<_>>();
    let no_op_bodies = no_op_bodies
        .iter()
        .map(|request| &request.request_json)
        .collect::<Vec<_>>();
    let intervention_bodies = intervention_bodies
        .iter()
        .map(|request| &request.request_json)
        .collect::<Vec<_>>();
    assert_eq!(baseline_bodies, no_op_bodies);
    assert_eq!(&baseline_bodies[..2], &intervention_bodies[..2]);
    assert_ne!(baseline_bodies[2], intervention_bodies[2]);

    let comparison = compare_paired_arms(&mut baseline, &mut no_op, &mut intervention).unwrap();
    assert_eq!(comparison.status, Claim2SlotStatus::Pass);
    assert!(comparison.baseline_noop_match);
    assert!(comparison.intervention_pre_treatment_match);
    for arm in [&baseline, &no_op, &intervention] {
        assert_eq!(
            evaluate_claim2_arm(&case, arm).unwrap().status,
            Claim2SlotStatus::Pass
        );
        assert!(arm
            .environment_receipts()
            .iter()
            .all(|receipt| !receipt.text.is_empty()));
        assert_eq!(arm.slots().len(), 3);
        assert!(arm
            .slots()
            .iter()
            .all(|slot| slot.status == Claim2SlotStatus::Pass));
    }

    let baseline_final_messages = &baseline_bodies[2];
    let intervention_final_messages = &intervention_bodies[2];
    let baseline_request: Value = serde_json::from_slice(baseline_final_messages).unwrap();
    let intervention_request: Value = serde_json::from_slice(intervention_final_messages).unwrap();
    let baseline_source = baseline_request["messages"]
        .as_array()
        .unwrap()
        .iter()
        .map(|message| message["content"].as_str().unwrap_or_default())
        .collect::<String>();
    let intervention_source = intervention_request["messages"]
        .as_array()
        .unwrap()
        .iter()
        .map(|message| message["content"].as_str().unwrap_or_default())
        .collect::<String>();
    let plan =
        fs::read_to_string(fixture_root().join("source/northstar-benefit-plan-2026.1.md")).unwrap();
    assert_eq!(baseline_source.matches(&plan).count(), 2);
    assert_eq!(intervention_source.matches(&plan).count(), 1);
}

#[test]
fn advancing_domain_pins_the_single_raw_output_and_each_selected_receipt() {
    let case_root = fixture_root();
    let case = load_cp07();
    let domain: Value = serde_json::from_slice(
        &fs::read(case_root.join("advancing-output-domain-v2.json")).unwrap(),
    )
    .unwrap();
    assert_eq!(domain["case_id"], "CP07");
    assert_eq!(domain["offline_only"], true);
    let points = domain["points"].as_array().unwrap();
    assert_eq!(points.len(), 2);
    for (index, action_id) in [
        "inspect_coverage_eligibility",
        "calculate_benefit_breakdown",
    ]
    .into_iter()
    .enumerate()
    {
        let point = &points[index];
        let raw = canonical_claim2_action_output(action_id);
        assert_eq!(point["request_slot"], index + 1);
        assert_eq!(point["expected_action_id"], action_id);
        assert_eq!(point["canonical_raw_utf8"], raw);
        assert_eq!(point["canonical_raw_sha256"], digest(raw.as_bytes()));
        assert_eq!(point["raw_language_cardinality"], 1);
        let receipt = fs::read(case_root.join(point["receipt_path"].as_str().unwrap())).unwrap();
        assert_eq!(point["receipt_sha256"], digest(&receipt));
        let transition = case
            .manifest()
            .action_menu
            .iter()
            .find(|transition| {
                transition.action_slot == (index + 1) as u8 && transition.action_id == action_id
            })
            .unwrap();
        assert_eq!(point["receipt_event_id"], transition.result_event_id);
        assert_eq!(point["state_after"], transition.state_after);
        assert!(!raw.ends_with('\n'));
    }
}

#[test]
fn noncanonical_advancing_spellings_fail_before_later_requests() {
    let case = load_cp07();
    let canonical = canonical_claim2_action_output("inspect_coverage_eligibility");
    let variants = [
        format!(" {canonical}"),
        format!("{canonical}\n"),
        "{\"action_id\": \"inspect_coverage_eligibility\"}".to_string(),
        "{\"action_id\":\"inspect_coverage_eligibility\",\"extra\":true}".to_string(),
    ];
    for raw in variants {
        let mut arm = Claim2ArmState::new(&case, Claim2ProjectionMode::Baseline);
        render_claim2_request(&case, &mut arm).unwrap();
        let evaluation = arm.record_output(&case, raw.clone()).unwrap().unwrap();
        assert_eq!(evaluation.status, Claim2SlotStatus::Fail);
        assert_eq!(
            arm.slots()[0].raw_assistant_output.as_deref(),
            Some(raw.as_str())
        );
        assert_eq!(
            arm.slots()[1].status,
            Claim2SlotStatus::NotExecutedAfterFailure
        );
        assert!(arm.slots()[2].status == Claim2SlotStatus::NotExecutedAfterFailure);
        assert!(render_claim2_request(&case, &mut arm).is_err());
    }
}

#[test]
fn exact_structured_evaluator_rejects_a_one_cent_answer_mutation() {
    let case = load_cp07();
    let mut answer = final_answer(&fixture_root());
    answer["benefit_limit"]["plan_payment_cents"] = Value::from(179999);
    let mut arm = Claim2ArmState::new(&case, Claim2ProjectionMode::Baseline);
    for action_id in [
        "inspect_coverage_eligibility",
        "calculate_benefit_breakdown",
    ] {
        render_claim2_request(&case, &mut arm).unwrap();
        assert!(arm
            .record_output(&case, canonical_claim2_action_output(action_id))
            .unwrap()
            .is_none());
    }
    render_claim2_request(&case, &mut arm).unwrap();
    let output = serde_json::json!({ "answer": answer }).to_string();
    let evaluation = arm.record_output(&case, output).unwrap().unwrap();
    assert_eq!(evaluation.status, Claim2SlotStatus::Fail);
    assert!(evaluation.final_answer_shape_valid);
    assert!(!evaluation.final_answer_passed);
    assert!(evaluation
        .failure_reasons
        .contains(&"final_answer_mismatch".to_string()));
}
