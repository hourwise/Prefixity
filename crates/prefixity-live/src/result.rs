//! Experiment result and conservative conclusion classification.
//!
//! The classification compares **observed structural prefix reuse**
//! (from `prefixity-core::compare`, in Prefixity's estimated-token unit)
//! with **provider-reported cache reuse** (from normalized usage, in the
//! provider's token unit) through their **proportions**. Absolute token
//! counts from different tokenizers are never subtracted from each other.
//!
//! Terminology: `structural_reuse_ratio` is the observed reusable-prefix
//! **POTENTIAL** in Prefixity's structural model — what a provider cache
//! *could* serve given perfect persistence of that prefix. It is not a
//! prediction of the exact provider cache-hit ratio. `provider_cache_reuse_ratio`
//! is the **REALIZED** provider cache reuse reported for that request
//! (best-effort, asynchronous persistence may lag or exceed structural
//! potential). `reuse_ratio_difference` is the realization/alignment gap
//! between those two observations.
//!
//! A single MATCH proves very little; the classification is deliberately
//! conservative and documented in `docs/phase-0/PHASE_0B_LIVE_VALIDATION.md`
//! and `docs/phase-0/PHASE_0B_FINDINGS.md`.

use prefixity_core::usage::{NormalizedUsage, SCHEMA_DEEPSEEK_CHAT_COMPLETIONS_V1};
use serde::{Deserialize, Serialize};

/// Conservative conclusion classification.
#[derive(Debug, Clone, Copy, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "SCREAMING_SNAKE_CASE")]
pub enum Conclusion {
    /// Structural reuse potential and realized provider cache reuse aligned
    /// closely for this observation.
    Match,
    /// Some provider reuse occurred but realized cache availability was
    /// materially below/above structural potential. This does NOT
    /// necessarily mean Prefixity's structural comparison was wrong —
    /// provider cache availability/state can differ.
    PartialMatch,
    /// One side observed effectively zero reuse while the other observed
    /// clearly substantial reuse. Must not be casually described as proof
    /// that structural analysis is incorrect; provider cache
    /// availability/state can differ.
    NoMatch,
    /// The provider did not expose enough data for a conclusion.
    Inconclusive,
    /// The provider response does not fit the registered normalizer.
    SchemaMismatch,
}

impl Conclusion {
    /// Human-readable label.
    pub fn as_str(&self) -> &'static str {
        match self {
            Conclusion::Match => "MATCH",
            Conclusion::PartialMatch => "PARTIAL_MATCH",
            Conclusion::NoMatch => "NO_MATCH",
            Conclusion::Inconclusive => "INCONCLUSIVE",
            Conclusion::SchemaMismatch => "SCHEMA_MISMATCH",
        }
    }
}

/// Per-request results captured during a live run.
#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct RequestResult {
    /// 1-based turn number.
    pub turn: usize,
    /// HTTP status observed.
    pub http_status: u16,
    /// Provider request id, if captured (safe).
    pub provider_request_id: Option<String>,
    /// The model string the provider returned, if any.
    pub model_returned: Option<String>,
    /// Start time (ISO-8601 UTC).
    pub started_at: String,
    /// Time until response headers arrived.
    pub time_to_headers_ms: u64,
    /// Time until the first body byte arrived (approximate), if measurable.
    pub time_to_first_body_byte_ms: Option<u64>,
    /// Total response time.
    pub total_ms: u64,
    /// Planned pre-request delay (ms) for this request (experimental settle
    /// control), recorded so result.json is auditable.
    pub pre_request_delay_ms: u64,
    /// Total generated bytes sent in the request.
    pub generated_bytes: u64,
    /// Prefixity's recorded token estimate for the request.
    pub prefixity_estimated_tokens: u64,
    /// Normalized provider usage.
    pub normalized_usage: NormalizedUsage,
    /// Normalizer notes/warnings.
    pub normalizer_warnings: Vec<String>,
    /// Artifact file names (relative to the run directory).
    pub trace_file: String,
    pub raw_usage_file: String,
}

/// Per consecutive-request-pair comparison.
///
/// Two measurement systems are preserved explicitly and are **never**
/// subtracted from each other:
///
/// * **Prefixity estimated unit** — Prefixity's chars/4 estimate
///   (`*_estimated_tokens` fields).
/// * **Provider token unit** — tokens reported by the provider
///   (`provider_reported_*` fields).
///
/// Classification compares the two reuse **proportions** (each relative to
/// its own denominator), not the absolute counts. `structural_reuse_ratio`
/// is the reusable-prefix **POTENTIAL** in Prefixity's structural model;
/// `provider_cache_reuse_ratio` is the **REALIZED** provider cache reuse for
/// that request; `reuse_ratio_difference` is the realization/alignment gap.
#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct PairResult {
    /// 1-based turn numbers of the pair.
    pub request_a: usize,
    pub request_b: usize,
    // --- Prefixity estimated unit (chars/4) ---
    /// Observed structurally reusable prefix, in Prefixity estimated tokens.
    pub observed_structural_reuse_estimated_tokens: u64,
    /// Request B's total input, in Prefixity estimated tokens.
    pub request_b_prefixity_estimated_input_tokens: u64,
    /// Observed reusable-prefix **POTENTIAL** in Prefixity's structural
    /// model:
    /// `observed_structural_reuse_estimated_tokens / request_b_prefixity_estimated_input_tokens`.
    /// This is NOT a prediction of the exact provider cache-hit ratio.
    pub structural_reuse_ratio: Option<f64>,
    // --- Provider token unit ---
    /// Provider-reported cache-read tokens for request B (normalized), if any.
    pub provider_reported_cache_read_tokens: Option<u64>,
    /// Provider-reported total input tokens for request B (normalized), if any.
    pub provider_reported_total_input_tokens: Option<u64>,
    /// **REALIZED** provider cache reuse:
    /// `provider_reported_cache_read_tokens / provider_reported_total_input_tokens`.
    pub provider_cache_reuse_ratio: Option<f64>,
    // --- Proportion comparison ---
    /// `|structural_reuse_ratio - provider_cache_reuse_ratio|` when both are
    /// available: the realization/alignment gap between structural potential
    /// and realized provider reuse. Replaces the old cross-tokenizer
    /// `difference` field, which subtracted provider tokens from Prefixity
    /// estimated tokens and mixed incompatible units.
    pub reuse_ratio_difference: Option<f64>,
    /// Whether this pair is a diagnostic pair or the experiment's PRIMARY
    /// (final) measurement pair, which drives the overall conclusion.
    pub role: PairRole,
    /// Per-pair conclusion (proportion-based).
    pub conclusion: Conclusion,
    /// Human-readable note, with measurement bases labelled and the
    /// potential-vs-realized distinction made explicit.
    pub note: String,
}

/// Whether a consecutive-request pair is diagnostic or the experiment's
/// primary (final) measurement pair.
///
/// Earlier pairs (e.g. A → B priming / cache-availability checks, or B → C
/// first-divergence diagnostics) are `Diagnostic`. The final pair is
/// `Primary` and is what the overall conclusion is based on. Diagnostic
/// pairs are never discarded — they are recorded evidence too.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "SCREAMING_SNAKE_CASE")]
pub enum PairRole {
    /// Non-final pair (priming / cache-availability / first-divergence
    /// diagnostics).
    Diagnostic,
    /// The final measurement pair; drives the overall conclusion.
    Primary,
}

impl PairRole {
    /// Human-readable label for reports.
    pub fn label(&self) -> &'static str {
        match self {
            PairRole::Diagnostic => "diagnostic",
            PairRole::Primary => "primary",
        }
    }
}

/// The full result of a live experiment. Serialized to `result.json`.
#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct ExperimentResult {
    /// Provider id.
    pub provider: String,
    /// Exact model id used.
    pub model: String,
    /// Scenario name.
    pub scenario: String,
    /// Number of requests actually completed.
    pub request_count: usize,
    /// Estimated input tokens for the whole experiment (Prefixity estimate).
    pub estimated_input_tokens: u64,
    /// Per-request results.
    pub requests: Vec<RequestResult>,
    /// Per-pair comparisons (empty for single-request scenarios).
    pub pairs: Vec<PairResult>,
    /// Overall conservative conclusion.
    pub conclusion: Conclusion,
    /// Human-readable summary.
    pub summary: String,
    /// Set when the run aborted early (e.g. transport error); partial
    /// artifacts remain reviewable.
    pub error: Option<String>,
}

/// Phase 0B **experimental** threshold: the maximum absolute reuse-ratio
/// distance (in percentage points; 0.10 = 10 points) between the structural
/// and provider reuse proportions that is still classified as MATCH. This is
/// a research threshold, not a scientifically validated tolerance.
pub const REUSE_RATIO_MATCH_TOLERANCE: f64 = 0.10;

/// A reuse proportion at or below this value is treated as "effectively
/// zero" (no meaningful reuse on that side).
pub const REUSE_RATIO_EFFECTIVELY_ZERO: f64 = 0.05;

/// A reuse proportion at or above this value is treated as "clearly
/// substantial" reuse.
pub const REUSE_RATIO_SUBSTANTIAL: f64 = 0.20;

/// `numerator / denominator`, or `None` when the denominator is zero (no
/// meaningful proportion exists).
pub fn reuse_ratio(numerator: u64, denominator: u64) -> Option<f64> {
    if denominator == 0 {
        None
    } else {
        Some(numerator as f64 / denominator as f64)
    }
}

/// Classify one pair from the two reuse proportions.
///
/// `structural_reuse_ratio` is the observed reusable-prefix **POTENTIAL** in
/// Prefixity's structural model (as a proportion of Prefixity's estimated
/// request input); `provider_cache_reuse_ratio` is the **REALIZED** provider
/// cache reuse (as a proportion of the provider's reported total input).
/// Absolute token counts from different tokenizers are not directly
/// comparable, so classification uses proportions only. If either proportion
/// is unavailable (missing provider figure or a zero Prefixity denominator),
/// the result is INCONCLUSIVE.
///
/// MATCH means the two observations aligned closely for this request;
/// PARTIAL_MATCH means some provider reuse occurred but realized cache
/// availability was materially below/above structural potential — it does
/// NOT necessarily mean Prefixity's structural comparison was wrong.
pub fn classify_pair(
    structural_reuse_ratio: Option<f64>,
    provider_cache_reuse_ratio: Option<f64>,
) -> Conclusion {
    let (Some(structural), Some(provider)) = (structural_reuse_ratio, provider_cache_reuse_ratio)
    else {
        // Missing provider figure, or zero Prefixity denominator.
        return Conclusion::Inconclusive;
    };
    // Both effectively zero: consistent "no reuse" observations.
    if structural <= REUSE_RATIO_EFFECTIVELY_ZERO && provider <= REUSE_RATIO_EFFECTIVELY_ZERO {
        return Conclusion::Match;
    }
    // One side effectively zero while the other is clearly substantial.
    if structural <= REUSE_RATIO_EFFECTIVELY_ZERO && provider >= REUSE_RATIO_SUBSTANTIAL {
        return Conclusion::NoMatch;
    }
    if provider <= REUSE_RATIO_EFFECTIVELY_ZERO && structural >= REUSE_RATIO_SUBSTANTIAL {
        return Conclusion::NoMatch;
    }
    // Otherwise compare the absolute (percentage-point) ratio distance.
    let distance = (structural - provider).abs();
    if distance <= REUSE_RATIO_MATCH_TOLERANCE {
        Conclusion::Match
    } else {
        Conclusion::PartialMatch
    }
}

/// A normalized usage category that a schema-smoke run may require for a
/// specific endpoint schema.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RequiredField {
    TotalInputTokens,
    FreshInputTokens,
    CacheReadTokens,
    CacheWriteTokens,
    OutputTokens,
}

/// The endpoint-schema-specific fields a schema-smoke must successfully
/// derive for a schema to be a MATCH.
///
/// The default (empty) set keeps the base behaviour — any successful
/// derivation counts — so later endpoint schemas can tighten their own
/// requirements here without changing the classifier. The DeepSeek
/// Chat Completions schema requires its defining input/cache categories;
/// completion/output tokens alone are not evidence that the schema matches.
pub fn schema_smoke_required_fields(schema: &str) -> &'static [RequiredField] {
    match schema {
        SCHEMA_DEEPSEEK_CHAT_COMPLETIONS_V1 => &[
            RequiredField::TotalInputTokens,
            RequiredField::FreshInputTokens,
            RequiredField::CacheReadTokens,
        ],
        _ => &[],
    }
}

/// Whether `normalized` successfully derived the given field.
fn required_field_derived(field: RequiredField, normalized: &NormalizedUsage) -> bool {
    match field {
        RequiredField::TotalInputTokens => normalized.total_input_tokens.is_some(),
        RequiredField::FreshInputTokens => normalized.fresh_input_tokens.is_some(),
        RequiredField::CacheReadTokens => normalized.cache_read_tokens.is_some(),
        RequiredField::CacheWriteTokens => normalized.cache_write_tokens.is_some(),
        RequiredField::OutputTokens => normalized.output_tokens.is_some(),
    }
}

/// Classify a schema-smoke run from the normalized usage.
pub fn classify_schema_smoke(normalized: &NormalizedUsage) -> Conclusion {
    if normalized.normalization_source == "unknown-schema" {
        return Conclusion::SchemaMismatch;
    }
    let required = schema_smoke_required_fields(&normalized.normalization_source);
    if !required.is_empty() {
        // Endpoint schema with explicit requirements: ALL must be derived.
        if required
            .iter()
            .all(|field| required_field_derived(*field, normalized))
        {
            return Conclusion::Match;
        }
        return Conclusion::SchemaMismatch;
    }
    // Base requirement for schemas without a specific set: any successful
    // derivation counts as a smoke match.
    let anything_derived = normalized.total_input_tokens.is_some()
        || normalized.fresh_input_tokens.is_some()
        || normalized.cache_read_tokens.is_some()
        || normalized.cache_write_tokens.is_some()
        || normalized.output_tokens.is_some();
    if anything_derived {
        Conclusion::Match
    } else {
        Conclusion::SchemaMismatch
    }
}

/// The overall experiment conclusion: schema-smoke conclusion if present,
/// otherwise the conclusion of the PRIMARY (final) measurement pair. For
/// four-turn DeepSeek late-divergence, the final pair C → D is the primary
/// persistence measurement; B → C remains recorded as a diagnostic pair.
pub fn overall_conclusion(schema_smoke: Option<Conclusion>, pairs: &[PairResult]) -> Conclusion {
    if let Some(conclusion) = schema_smoke {
        return conclusion;
    }
    pairs
        .last()
        .map(|pair| pair.conclusion)
        .unwrap_or(Conclusion::Inconclusive)
}

