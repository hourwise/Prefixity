//! Experiment result and conservative conclusion classification.
//!
//! The classification compares **observed structural prefix reuse** (from
//! `prefixity-core::compare`) with **provider-reported cache reuse** (from
//! normalized usage). A single MATCH proves very little; the classification
//! is deliberately conservative and documented in
//! `docs/phase-0/PHASE_0B_LIVE_VALIDATION.md`.

use prefixity_core::usage::NormalizedUsage;
use serde::Serialize;

/// Conservative conclusion classification.
#[derive(Debug, Clone, Copy, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "SCREAMING_SNAKE_CASE")]
pub enum Conclusion {
    /// Provider behaviour broadly corresponds to the structural prediction.
    Match,
    /// Some reuse appears but differs materially from the prediction.
    PartialMatch,
    /// Provider behaviour contradicts the structural prediction.
    NoMatch,
    /// The provider did not expose enough data for a conclusion.
    Inconclusive,
    /// The provider response does not fit the registered normalizer.
    SchemaMismatch,
}

impl Conclusion {
    /// Human-readable label.
    pub fn as_str(&self) -> &'static str {
        match self {
            Conclusion::Match => "MATCH",
            Conclusion::PartialMatch => "PARTIAL_MATCH",
            Conclusion::NoMatch => "NO_MATCH",
            Conclusion::Inconclusive => "INCONCLUSIVE",
            Conclusion::SchemaMismatch => "SCHEMA_MISMATCH",
        }
    }
}

/// Per-request results captured during a live run.
#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct RequestResult {
    /// 1-based turn number.
    pub turn: usize,
    /// HTTP status observed.
    pub http_status: u16,
    /// Provider request id, if captured (safe).
    pub provider_request_id: Option<String>,
    /// The model string the provider returned, if any.
    pub model_returned: Option<String>,
    /// Start time (ISO-8601 UTC).
    pub started_at: String,
    /// Time until response headers arrived.
    pub time_to_headers_ms: u64,
    /// Time until the first body byte arrived (approximate), if measurable.
    pub time_to_first_body_byte_ms: Option<u64>,
    /// Total response time.
    pub total_ms: u64,
    /// Total generated bytes sent in the request.
    pub generated_bytes: u64,
    /// Prefixity's recorded token estimate for the request.
    pub prefixity_estimated_tokens: u64,
    /// Normalized provider usage.
    pub normalized_usage: NormalizedUsage,
    /// Normalizer notes/warnings.
    pub normalizer_warnings: Vec<String>,
    /// Artifact file names (relative to the run directory).
    pub trace_file: String,
    pub raw_usage_file: String,
}

/// Per consecutive-request-pair comparison.
#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct PairResult {
    /// 1-based turn numbers of the pair.
    pub request_a: usize,
    pub request_b: usize,
    /// Observed structural reusable-prefix tokens (estimated tokens).
    pub observed_structural_reuse_tokens: u64,
    /// Provider-reported cache-read tokens for request B (normalized), if any.
    pub provider_reported_cache_read_tokens: Option<u64>,
    /// `reported - observed` when both are available.
    pub difference: Option<i64>,
    /// Per-pair conclusion.
    pub conclusion: Conclusion,
    /// Human-readable note.
    pub note: String,
}

/// The full result of a live experiment. Serialized to `result.json`.
#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct ExperimentResult {
    /// Provider id.
    pub provider: String,
    /// Exact model id used.
    pub model: String,
    /// Scenario name.
    pub scenario: String,
    /// Number of requests actually completed.
    pub request_count: usize,
    /// Estimated input tokens for the whole experiment (Prefixity estimate).
    pub estimated_input_tokens: u64,
    /// Per-request results.
    pub requests: Vec<RequestResult>,
    /// Per-pair comparisons (empty for single-request scenarios).
    pub pairs: Vec<PairResult>,
    /// Overall conservative conclusion.
    pub conclusion: Conclusion,
    /// Human-readable summary.
    pub summary: String,
    /// Set when the run aborted early (e.g. transport error); partial
    /// artifacts remain reviewable.
    pub error: Option<String>,
}

/// Tolerance for treating provider-reported cache reads as matching observed
/// structural reuse, expressed as a ratio of the difference to the observed
/// value.
pub const MATCH_RATIO_TOLERANCE: f64 = 0.25;

/// Classify one pair from provider-reported cache reads vs observed
/// structural reuse.
pub fn classify_pair(
    reported_cache_read: Option<u64>,
    observed_structural_reuse: u64,
) -> Conclusion {
    let Some(reported) = reported_cache_read else {
        return Conclusion::Inconclusive;
    };
    if reported == 0 && observed_structural_reuse == 0 {
        Conclusion::Match
    } else if reported == 0 {
        // We predicted structural reuse, but the provider reports none.
        Conclusion::NoMatch
    } else if observed_structural_reuse == 0 {
        // Provider reports reuse where no structural reuse was observed.
        Conclusion::NoMatch
    } else {
        let difference = reported.abs_diff(observed_structural_reuse);
        let ratio = difference as f64 / observed_structural_reuse as f64;
        if ratio <= MATCH_RATIO_TOLERANCE {
            Conclusion::Match
        } else {
            Conclusion::PartialMatch
        }
    }
}

/// Classify a schema-smoke run from the normalized usage.
pub fn classify_schema_smoke(normalized: &NormalizedUsage) -> Conclusion {
    if normalized.normalization_source == "unknown-schema" {
        return Conclusion::SchemaMismatch;
    }
    let anything_derived = normalized.total_input_tokens.is_some()
        || normalized.fresh_input_tokens.is_some()
        || normalized.cache_read_tokens.is_some()
        || normalized.cache_write_tokens.is_some()
        || normalized.output_tokens.is_some();
    if anything_derived {
        Conclusion::Match
    } else {
        Conclusion::SchemaMismatch
    }
}

/// The overall experiment conclusion: schema-smoke conclusion if present,
/// otherwise the conclusion of the final pair (most representative of
/// steady-state behaviour).
pub fn overall_conclusion(schema_smoke: Option<Conclusion>, pairs: &[PairResult]) -> Conclusion {
    if let Some(conclusion) = schema_smoke {
        return conclusion;
    }
    pairs
        .last()
        .map(|pair| pair.conclusion)
        .unwrap_or(Conclusion::Inconclusive)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn pair_classification_is_conservative() {
        // Both zero -> Match.
        assert_eq!(classify_pair(Some(0), 0), Conclusion::Match);
        // Predicted reuse, provider none -> NoMatch.
        assert_eq!(classify_pair(Some(0), 1000), Conclusion::NoMatch);
        // Provider reuse, predicted none -> NoMatch.
        assert_eq!(classify_pair(Some(1000), 0), Conclusion::NoMatch);
        // Close match -> Match.
        assert_eq!(classify_pair(Some(1000), 1000), Conclusion::Match);
        assert_eq!(classify_pair(Some(1100), 1000), Conclusion::Match);
        // Material difference -> PartialMatch.
        assert_eq!(classify_pair(Some(500), 1000), Conclusion::PartialMatch);
        // No provider data -> Inconclusive.
        assert_eq!(classify_pair(None, 1000), Conclusion::Inconclusive);
    }

    #[test]
    fn schema_smoke_classification() {
        let mut normalized = NormalizedUsage {
            total_input_tokens: Some(100),
            fresh_input_tokens: Some(100),
            cache_read_tokens: None,
            cache_write_tokens: None,
            output_tokens: Some(8),
            normalization_source: "openai-chat-completions-v1".to_string(),
            explanation: "ok".to_string(),
        };
        assert_eq!(classify_schema_smoke(&normalized), Conclusion::Match);

        normalized.normalization_source = "unknown-schema".to_string();
        assert_eq!(
            classify_schema_smoke(&normalized),
            Conclusion::SchemaMismatch
        );

        let empty = NormalizedUsage {
            total_input_tokens: None,
            fresh_input_tokens: None,
            cache_read_tokens: None,
            cache_write_tokens: None,
            output_tokens: None,
            normalization_source: "openai-chat-completions-v1".to_string(),
            explanation: "nothing derivable".to_string(),
        };
        assert_eq!(classify_schema_smoke(&empty), Conclusion::SchemaMismatch);
    }

    #[test]
    fn overall_uses_schema_smoke_or_last_pair() {
        let pair = PairResult {
            request_a: 1,
            request_b: 2,
            observed_structural_reuse_tokens: 100,
            provider_reported_cache_read_tokens: Some(100),
            difference: Some(0),
            conclusion: Conclusion::Match,
            note: "n".to_string(),
        };
        assert_eq!(
            overall_conclusion(
                Some(Conclusion::SchemaMismatch),
                std::slice::from_ref(&pair)
            ),
            Conclusion::SchemaMismatch
        );
        assert_eq!(
            overall_conclusion(None, std::slice::from_ref(&pair)),
            Conclusion::Match
        );
        assert_eq!(overall_conclusion(None, &[]), Conclusion::Inconclusive);
    }
}
